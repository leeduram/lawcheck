  static const String _defaultCategory = '기타';

  /// 키워드 리스트로 카테고리 1개 반환
  static String classify(List<String> keywords) {
    final scores = <String, int>{};

    for (final keyword in keywords) {
      _categoryKeywords.forEach((category, matchWords) {
        for (final word in matchWords) {
          if (keyword.contains(word)) {
            scores[category] = (scores[category] ?? 0) + 1;
          }
        }
      });
    }

    if (scores.isEmpty) return _defaultCategory;

    final sorted = scores.entries.toList()
      ..sort((a, b) => b.value.compareTo(a.value));
    return sorted.first.key;
  }

  /// 전체 카테고리 목록
  static List<String> get allCategories =>
      [..._categoryKeywords.keys, _defaultCategory];
